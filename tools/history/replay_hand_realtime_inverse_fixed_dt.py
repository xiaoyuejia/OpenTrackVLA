def capture_color_mask_snapshot_stable(
    env,
    include_masks: bool,
    attempts: int = 8,
    mode: str = "sequential",
    render_sync_s: float = 0.0,
) -> tuple[np.ndarray, list[np.ndarray | None]]:
    """Capture a complete observation with bounded retries.

    ``batch`` retains the old, faster single UnrealCV request.  ``sequential``
    deliberately uses one request per pose/image.  The latter avoids the UE
    5.6/UnrealCV failure mode where a large mixed batch disconnects the socket
    and the legacy decoder silently returns a truncated response list.
    """
    last_error: Exception | None = None
    for attempt in range(1, max(1, int(attempts)) + 1):
        try:
            if mode == "batch":
                observation, masks = capture_color_mask_snapshot(env, include_masks=include_masks)
            else:
                observation, masks = capture_color_mask_snapshot_sequential(
                    env, include_masks=include_masks, render_sync_s=render_sync_s
                )
            required = [idx for idx, cam_id in enumerate(env.unwrapped.cam_list) if cam_id is not None and cam_id >= 0]
            if required and len(observation) <= max(required):
                raise RuntimeError(
                    f"incomplete RGB batch: got={len(observation)} required_camera_index={max(required)}"
                )
            if include_masks:
                missing_masks = [idx for idx in required if idx >= len(masks) or masks[idx] is None]
                if missing_masks:
                    raise RuntimeError(f"incomplete exact-mask snapshot for agent indices {missing_masks}")
            return observation, masks
        except Exception as exc:
            last_error = exc
            if attempt >= max(1, int(attempts)):
                break
            print(
                f"[snapshot] transient UnrealCV failure attempt={attempt}/{attempts}: {exc}; retrying",
                flush=True,
            )
            time.sleep(0.25 * attempt)
    raise RuntimeError(f"UnrealCV snapshot failed after {attempts} attempts") from last_error


def capture_color_mask_snapshot_sequential(
    env,
    include_masks: bool,
    render_sync_s: float = 0.0,
) -> tuple[np.ndarray, list[np.ndarray | None]]:
    """Stable alternative to ``get_pose_img_batch``.

    Do not use the convenience ``get_obj_*`` helpers here: they retry a
    disconnected socket forever.  A failed request must propagate to the
    bounded snapshot retry / episode watchdog, so a bad UE instance cannot
    stall the resumable batch forever.
    """
    unwrapped = env.unwrapped
    unrealcv = unwrapped.unrealcv

    def request(command: str, decoder, label: str):
        response = unrealcv.client.request(command)
        if response is None:
            raise RuntimeError(f"no UnrealCV response for {label}")
        try:
            return decoder(response)
        except Exception as exc:
            raise RuntimeError(f"invalid UnrealCV response for {label}: {exc}") from exc

    obj_poses: list[list[float]] = []
    for object_name in unwrapped.player_list:
        location = request(
            f"vget /object/{object_name}/location",
            unrealcv.decoder.string2floats,
            f"object location {object_name}",
        )
        rotation = request(
            f"vget /object/{object_name}/rotation",
            unrealcv.decoder.string2floats,
            f"object rotation {object_name}",
        )
        if len(location) < 3 or len(rotation) < 3:
            raise RuntimeError(f"incomplete pose for {object_name}: location={location}, rotation={rotation}")
        obj_poses.append(location + rotation)

    images: list[np.ndarray] = []
    mask_by_agent: list[np.ndarray | None] = [None] * len(unwrapped.cam_list)
    for agent_idx, cam_id in enumerate(unwrapped.cam_list):
        if cam_id is None or cam_id < 0:
            images.append(np.zeros((unwrapped.resolution[1], unwrapped.resolution[0], 3), dtype=np.uint8))
            continue
        color = request(
            f"vget /camera/{cam_id}/lit bmp",
            lambda payload: unrealcv.decoder.decode_img(payload, "bmp"),
            f"camera {cam_id} RGB",
        )
        if render_sync_s > 0:
            time.sleep(render_sync_s)
        if not isinstance(color, np.ndarray) or color.ndim != 3:
            raise RuntimeError(f"invalid RGB image for camera {cam_id}")
        images.append(color)
        if include_masks:
            mask = request(
                f"vget /camera/{cam_id}/object_mask png",
                lambda payload: unrealcv.decoder.decode_img(payload, "png"),
                f"camera {cam_id} mask",
            )
            if render_sync_s > 0:
                time.sleep(render_sync_s)
            if not isinstance(mask, np.ndarray) or mask.ndim < 2:
                raise RuntimeError(f"invalid mask image for camera {cam_id}")
            mask_by_agent[agent_idx] = mask

    observation = np.asarray(images)
    unwrapped.obj_poses = obj_poses
    unwrapped.img_show = unwrapped.prepare_img2show(unwrapped.protagonist_id, observation)
    return observation, mask_by_agent


def body_xy_velocity(before: list[float], after: list[float], dt: float) -> np.ndarray:
    """Measured local [forward, right] velocity in m/s."""
    world = (np.asarray(after[:2], dtype=float) - np.asarray(before[:2], dtype=float)) / UNREAL_UNITS_PER_METER
    yaw = math.radians(float(before[4]))
    return np.asarray(
        [math.cos(yaw) * world[0] + math.sin(yaw) * world[1], -math.sin(yaw) * world[0] + math.cos(yaw) * world[1]],
        dtype=float,
    ) / max(float(dt), 1e-6)


def reference_velocity(actual: list[float], reference: list[float], dt: float) -> np.ndarray:
    return body_xy_velocity(actual, reference, dt)


def body_velocity_between(start: list[float], end: list[float], body_yaw_deg: float, dt: float) -> np.ndarray:
    """Reference XY velocity expressed in an explicitly chosen body frame."""
    world = (np.asarray(end[:2], dtype=float) - np.asarray(start[:2], dtype=float)) / UNREAL_UNITS_PER_METER
    yaw = math.radians(float(body_yaw_deg))
    return np.asarray(
        [math.cos(yaw) * world[0] + math.sin(yaw) * world[1], -math.sin(yaw) * world[0] + math.cos(yaw) * world[1]],
        dtype=float,
    ) / max(float(dt), 1e-6)


def realized_base_velocity(before: list[float], after: list[float], dt: float) -> list[float]:
    """Actual [forward, right, yaw_rate] produced by one fixed UE step."""
    xy = body_xy_velocity(before, after, dt)
    yaw_rate = math.radians(wrap_deg(float(after[4]) - float(before[4]))) / max(float(dt), 1e-6)
    return [float(xy[0]), float(xy[1]), float(yaw_rate)]


def local_waypoints(poses_after_action: list[list[float]], start_index: int, horizon: int) -> tuple[list[list[float]], list[int]]:
    """Future replay poses relative to the current after-action pose.

    These are saved as an auditable geometric label. The training builder still
    derives its own labels from ``base_velocity`` so its existing contract is
    unchanged.
    """
    origin = poses_after_action[start_index]
    yaw0 = math.radians(float(origin[4]))
    points: list[list[float]] = [[0.0, 0.0, 0.0]]
    valid: list[int] = [1]
    for offset in range(1, horizon + 1):
        idx = start_index + offset
        if idx >= len(poses_after_action):
            points.append(points[-1].copy())
            valid.append(0)
            continue
        pose = poses_after_action[idx]
        dx = (float(pose[0]) - float(origin[0])) / UNREAL_UNITS_PER_METER
        dy = (float(pose[1]) - float(origin[1])) / UNREAL_UNITS_PER_METER
        points.append([
            float(math.cos(yaw0) * dx + math.sin(yaw0) * dy),
            float(-math.sin(yaw0) * dx + math.cos(yaw0) * dy),
            float(math.radians(wrap_deg(float(pose[4]) - float(origin[4])))),
        ])
        valid.append(1)
    return points, valid


def clamp(value: float, limit: float) -> tuple[float, bool]:
    limit = max(0.0, float(limit))
    result = float(np.clip(float(value), -limit, limit))
    return result, abs(result - float(value)) > 1e-9


class AdaptiveGroundSpeedModel:
    """Online scalar model for the delayed ground forward-speed actuator."""

    def __init__(self) -> None:
        self.theta = np.asarray([0.0, 1.0, 0.0], dtype=float)  # [a, b, c]
        self.covariance = np.diag([4.0, 2.0, 1.0]).astype(float)
        self.previous_velocity: float | None = None
        self.previous_command: float | None = None
        self.samples = 0

    def update(self, velocity: float) -> None:
        if self.previous_velocity is not None and self.previous_command is not None:
            phi = np.asarray([self.previous_velocity, self.previous_command, 1.0], dtype=float)
            denom = 1.0 + float(phi @ self.covariance @ phi)
            gain = (self.covariance @ phi) / max(denom, 1e-8)
            residual = float(velocity - phi @ self.theta)
            self.theta = self.theta + gain * residual
            self.theta[0] = float(np.clip(self.theta[0], 0.0, 0.95))
            self.theta[1] = float(np.clip(self.theta[1], 0.10, 1.50))
            self.theta[2] = float(np.clip(self.theta[2], -0.40, 0.40))
            self.covariance = (np.eye(3) - np.outer(gain, phi)) @ self.covariance
            self.samples += 1
        self.previous_velocity = float(velocity)

    def inverse_command(self, desired_next_velocity: float, current_velocity: float) -> float:
        a, b, c = [float(value) for value in self.theta]
        return float((desired_next_velocity - a * current_velocity - c) / max(b, 0.10))

    def set_command(self, command: float) -> None:
        self.previous_command = float(command)


def ground_control(
    actual: list[float], reference_before: list[float], reference_after: list[float], reference_after_next: list[float],
    dt: float, yaw_gain: float, max_speed: float, max_turn: float, translation_delay_steps: int,
    feedback_time_s: float, control_mode: str, vector_min_speed_mps: float,
    vector_max_heading_delta_deg: float, reference_lookahead: list[float], reverse_mode: bool,
    reverse_enter_deg: float, reverse_exit_deg: float, heading_goal_deg: float | None,
    heading_goal_rate_deg: float, turn_slowdown_floor: float, heading_deadband_deg: float,
    max_forward_feedback_mps: float, speed_model: str, adaptive_speed_model: AdaptiveGroundSpeedModel | None,
    current_forward_velocity: float,
) -> tuple[list[float], dict[str, Any]]:
    if translation_delay_steps == 0:
        source_velocity = body_velocity_between(reference_before, reference_after, float(actual[4]), dt)
    else:
        # Empirically, ground ``speed`` sent at t controls the translation at
        # t+1, while turn is applied in t.  Preview the source's next pose
        # transition rather than asking an already-sent command to fix t.
        source_velocity = body_velocity_between(reference_after, reference_after_next, float(actual[4]), dt)
    raw_position_feedback = body_velocity_between(
        actual,
        reference_before,
        float(actual[4]),
        max(float(feedback_time_s), dt),
    )
    position_feedback = raw_position_feedback.copy()
    position_feedback[0] = float(np.clip(
        position_feedback[0],
        -float(max_forward_feedback_mps),
        float(max_forward_feedback_mps),
    ))
    desired_body = source_velocity + position_feedback
    source_yaw_delta = wrap_deg(float(reference_after[4]) - float(actual[4]))
    if control_mode == "source_yaw":
        if speed_model == "adaptive_inverse":
            if adaptive_speed_model is None:
                raise RuntimeError("adaptive ground speed model is unavailable")
            speed_target = adaptive_speed_model.inverse_command(
                float(desired_body[0]), current_forward_velocity
            )
        else:
            speed_target = float(desired_body[0])
        yaw_delta = source_yaw_delta
    elif control_mode in {"vector_2d", "vector_2d_stable", "vector_2d_lookahead", "vector_2d_damped"}:
        # The ground BP is still a unicycle: it has no lateral actuator.  We
        # approximate a 2D velocity command by steering toward the requested
        # body-vector direction and using its magnitude as forward speed.
        vector_norm = float(np.linalg.norm(desired_body))
        vector_yaw_delta = math.degrees(math.atan2(float(desired_body[1]), float(desired_body[0])))
        if control_mode == "vector_2d":
            speed_target = vector_norm
            yaw_delta = vector_yaw_delta
        elif control_mode == "vector_2d_stable" and vector_norm < float(vector_min_speed_mps):
            # A nearly-zero vector has no reliable direction. Preserve source
            # heading and avoid a heading flip caused by atan2(very small y,x).
            speed_target = float(desired_body[0])
            yaw_delta = source_yaw_delta
        elif control_mode == "vector_2d_stable":
            # A unicycle can realize a behind-vector by reversing, without a
            # 180-degree heading flip. Keep the heading correction bounded so
            # feedback noise cannot create alternating full-rate turns.
            speed_target = vector_norm
            yaw_delta = vector_yaw_delta
            if yaw_delta > 90.0:
                yaw_delta -= 180.0
                speed_target = -speed_target
            elif yaw_delta < -90.0:
                yaw_delta += 180.0
                speed_target = -speed_target
            yaw_delta = float(np.clip(yaw_delta, -vector_max_heading_delta_deg, vector_max_heading_delta_deg))
        else:
            # Heading is derived from a spatial lookahead, not from the
            # frame-to-frame feedback vector. This removes atan2 direction
            # chatter when lateral feedback crosses zero.
            lookahead_body = body_velocity_between(
                actual,
                reference_lookahead,
                float(actual[4]),
                1.0,
            )
            lookahead_distance = float(np.linalg.norm(lookahead_body))
            raw_heading_delta = math.degrees(
                math.atan2(float(lookahead_body[1]), float(lookahead_body[0]))
            ) if lookahead_distance >= float(vector_min_speed_mps) else source_yaw_delta
            abs_raw = abs(raw_heading_delta)
            if reverse_mode:
                next_reverse_mode = abs_raw >= float(reverse_exit_deg)
            else:
                next_reverse_mode = abs_raw > float(reverse_enter_deg)
            if next_reverse_mode:
                raw_heading_delta = wrap_deg(raw_heading_delta - 180.0)
                speed_target = -vector_norm
            else:
                speed_target = vector_norm
            desired_heading_goal = float(actual[4] + raw_heading_delta)
            if control_mode == "vector_2d_damped":
                if heading_goal_deg is None:
                    next_heading_goal = float(actual[4])
                else:
                    next_heading_goal = float(
                        heading_goal_deg
                        + np.clip(
                            wrap_deg(desired_heading_goal - heading_goal_deg),
                            -heading_goal_rate_deg,
                            heading_goal_rate_deg,
                        )
                    )
                yaw_delta = wrap_deg(next_heading_goal - float(actual[4]))
                # Brake while turning. Sending full delayed speed into a large
                # heading correction is the source of the ground oscillation.
                speed_target *= max(
                    float(turn_slowdown_floor),
                    math.cos(math.radians(abs(yaw_delta))),
                )
            else:
                next_heading_goal = desired_heading_goal
                yaw_delta = raw_heading_delta
            yaw_delta = float(np.clip(yaw_delta, -vector_max_heading_delta_deg, vector_max_heading_delta_deg))
            if control_mode == "vector_2d_damped" and abs(yaw_delta) < float(heading_deadband_deg):
                yaw_delta = 0.0
    else:
        raise ValueError(f"unsupported ground control mode: {control_mode}")
    speed, speed_sat = clamp(speed_target, max_speed)
    unconstrained_turn = yaw_delta / max(float(yaw_gain), 1e-9)
    turn, turn_sat = clamp(unconstrained_turn, max_turn)
    return [turn, speed * UNREAL_UNITS_PER_METER], {
        "translation_delay_steps": int(translation_delay_steps),
        "control_mode": control_mode,
        "source_preview_body_velocity_mps": source_velocity.tolist(),
        "raw_position_feedback_body_velocity_mps": raw_position_feedback.tolist(),
        "position_feedback_body_velocity_mps": position_feedback.tolist(),
        "desired_body_velocity_mps": desired_body.tolist(),
        "unexecutable_lateral_velocity_mps": float(desired_body[1]),
        "source_yaw_delta_deg": source_yaw_delta,
        "vector_yaw_delta_deg": vector_yaw_delta if control_mode in {"vector_2d", "vector_2d_stable"} else None,
        "command_yaw_delta_deg": yaw_delta,
        "lookahead_heading_distance_m": (
            lookahead_distance if control_mode == "vector_2d_lookahead" else None
        ),
        "reverse_mode": bool(next_reverse_mode) if control_mode in {"vector_2d_lookahead", "vector_2d_damped"} else False,
        "heading_goal_deg": (
            next_heading_goal if control_mode in {"vector_2d_lookahead", "vector_2d_damped"} else None
        ),
        "desired_yaw_delta_deg": yaw_delta,
        "unconstrained_turn_command_deg": unconstrained_turn,
        "speed_saturated": speed_sat,
        "turn_saturated": turn_sat,
        "speed_model": speed_model,
        "measured_forward_velocity_mps": float(current_forward_velocity),
        "adaptive_speed_model": (
            {
                "a": float(adaptive_speed_model.theta[0]),
                "b": float(adaptive_speed_model.theta[1]),
                "c": float(adaptive_speed_model.theta[2]),
                "samples": int(adaptive_speed_model.samples),
            }
            if adaptive_speed_model is not None
            else None
        ),
    }


def drone_control(
    actual: list[float], previous_actual: list[float] | None, reference: list[float], dt: float, args: argparse.Namespace
) -> tuple[list[float], dict[str, Any]]:
    desired_velocity = reference_velocity(actual, reference, dt)
    measured_velocity = np.zeros(2, dtype=float) if previous_actual is None else body_xy_velocity(previous_actual, actual, dt)
    a_xy = np.asarray([args.drone_a_forward, args.drone_a_lateral], dtype=float)
    b_xy = np.asarray([args.drone_b_forward, args.drone_b_lateral], dtype=float)
    unconstrained_velocity_command = (desired_velocity - a_xy * measured_velocity) / np.maximum(b_xy, 1e-6)
    command_velocity = np.empty(2, dtype=float)
    saturation = []
    for axis in range(2):
        command_velocity[axis], clipped = clamp(unconstrained_velocity_command[axis], args.drone_max_command_mps)
        saturation.append(clipped)

    omega_measured = 0.0
    if previous_actual is not None:
        omega_measured = math.radians(wrap_deg(float(actual[4]) - float(previous_actual[4]))) / dt
    omega_desired = math.radians(wrap_deg(float(reference[4]) - float(actual[4]))) / dt
    yaw_unconstrained = (omega_desired - args.drone_yaw_a * omega_measured) / max(args.drone_yaw_b, 1e-6)
    yaw_command, yaw_sat = clamp(yaw_unconstrained, args.drone_max_yaw_command_radps)
    action = [float(command_velocity[0] * dt), float(command_velocity[1] * dt), 0.0, float(yaw_command)]
    predicted_velocity = a_xy * measured_velocity + b_xy * command_velocity
    return action, {
        "desired_body_velocity_mps": desired_velocity.tolist(),
        "measured_body_velocity_mps": measured_velocity.tolist(),
        "unconstrained_body_velocity_command_mps": unconstrained_velocity_command.tolist(),
        "commanded_body_velocity_mps": command_velocity.tolist(),
        "predicted_next_body_velocity_mps": predicted_velocity.tolist(),
        "desired_yaw_rate_radps": omega_desired,
        "measured_yaw_rate_radps": omega_measured,
        "unconstrained_yaw_command_radps": yaw_unconstrained,
        "yaw_command_radps": yaw_command,
        "translation_saturated": saturation,
        "yaw_saturated": yaw_sat,
        "z_reference_error_m": float((reference[2] - actual[2]) / UNREAL_UNITS_PER_METER),
    }



def _argv_value(name: str, default: str) -> str:
    prefix = f"{name}="
    for i, value in enumerate(sys.argv):
        if value == name and i + 1 < len(sys.argv):
            return sys.argv[i + 1]
        if value.startswith(prefix):
            return value[len(prefix):]
    return default



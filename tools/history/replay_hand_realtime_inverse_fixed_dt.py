"""Closed-loop inverse-dynamics replay of a recorded hand_realtime episode.

Adjacent source poses are treated as samples separated by ``--dt``.  Only the
initial poses/cameras are restored.  Every later pose is produced by a fixed
UE resume/pause pulse and commands computed from the *current replay state*.

This is deliberately a dynamics-feasibility experiment, not an evaluation
policy: it exposes where a recorded transition cannot be generated by the
available BP command space and the calibrated drone first-order response.
"""


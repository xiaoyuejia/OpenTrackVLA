def _require(rows: list[dict[str, Any]], index: int, key: str) -> list[float]:
    pose = valid_pose(rows[index].get(key))
    if pose is None:
        raise ValueError(f"source step {index + 1} has no valid {key}")
    return pose


def _reference(rows: list[dict[str, Any]], index: int, key: str) -> list[float]:
    return next_or_after(rows, index, key)


def plot_results(rows: list[dict[str, Any]], output: Path) -> None:
    """Small dependency-free-enough diagnostic plot, generated after the run."""
    try:
        import matplotlib.pyplot as plt
    except Exception as exc:
        print(f"[plot] unavailable: {exc}", flush=True)
        return
    t = np.asarray([r["step"] for r in rows], dtype=float) * float(rows[0]["dt"])
    fig, axes = plt.subplots(2, 2, figsize=(12, 8), constrained_layout=True)
    for name, color in (("target", "tab:green"), ("robotdog", "tab:orange"), ("drone", "tab:blue")):
        reference = np.asarray([r[f"source_{name}_pose_after_action"][:2] for r in rows], dtype=float) / UNREAL_UNITS_PER_METER
        actual = np.asarray([r[f"{name}_pose_after_action"][:2] for r in rows], dtype=float) / UNREAL_UNITS_PER_METER
        axes[0, 0].plot(reference[:, 0], reference[:, 1], "--", color=color, alpha=.65, label=f"{name} source")
        axes[0, 0].plot(actual[:, 0], actual[:, 1], color=color, label=f"{name} replay")
        axes[0, 1].plot(t, [r[f"{name}_after_error_m"] for r in rows], color=color, label=name)
        axes[1, 0].plot(t, [r[f"{name}_yaw_after_error_deg"] for r in rows], color=color, label=name)
    axes[1, 1].plot(t, [int(any(r["drone_inverse"]["translation_saturated"])) for r in rows], label="drone translation sat")
    axes[1, 1].plot(t, [int(r["drone_inverse"]["yaw_saturated"]) for r in rows], label="drone yaw sat")
    axes[1, 1].plot(t, [int(r["target_inverse"]["speed_saturated"] or r["target_inverse"]["turn_saturated"]) for r in rows], label="human saturation")
    axes[1, 1].plot(t, [int(r["robotdog_inverse"]["speed_saturated"] or r["robotdog_inverse"]["turn_saturated"]) for r in rows], label="dog saturation")
    axes[0, 0].set(xlabel="world x (m)", ylabel="world y (m)", title="source vs replay trajectory")
    axes[0, 1].set(xlabel="time (s)", ylabel="3D error (m)", title="after-action position error")
    axes[1, 0].set(xlabel="time (s)", ylabel="yaw error (deg)", title="after-action yaw error")
    axes[1, 1].set(xlabel="time (s)", ylabel="saturated (0/1)", title="inverse command saturation")
    for axis in axes.flat:
        axis.grid(True, alpha=.25)
        axis.legend(fontsize=8)
    fig.savefig(output, dpi=150)
    plt.close(fig)


def bbox_center_metrics(bbox: list[int], width: int, height: int) -> tuple[float, bool]:
    """Return normalized center error and a conservative centered flag."""
    if len(bbox) < 4 or int(bbox[2]) <= 0 or int(bbox[3]) <= 0:
        return 1.0, False
    cx = float(bbox[0]) + 0.5 * float(bbox[2])
    cy = float(bbox[1]) + 0.5 * float(bbox[3])
    error = math.hypot(cx - 0.5 * width, cy - 0.5 * height) / max(math.hypot(width, height), 1.0)
    return float(error), bool(error <= 0.15)


def xy_distance_m(first: list[float], second: list[float]) -> float:
    return float(np.linalg.norm(np.asarray(first[:2], dtype=float) - np.asarray(second[:2], dtype=float)) / UNREAL_UNITS_PER_METER)


def write_training_records(
    output_dir: Path,
    episode: str,
    rows: list[dict[str, Any]],
    args: argparse.Namespace,
    instruction: str,
) -> None:
    """Emit the exact multi-agent recording contract consumed by make_tracking_data.

    ``base_velocity`` intentionally means *measured replay response*, while
    ``commanded_base_velocity`` and ``env_action`` retain the inverse command.
    This prevents the trainer from silently learning an infeasible command as
    though it were a realized motion.
    """
    if not rows:
        return
    drone_pitch = float(args.drone_camera_pitch) if args.drone_camera_pitch is not None else float(rows[0].get("drone_camera_pitch", -40.0))
    drone_yaw_offset = float(args.drone_camera_yaw_offset) if args.drone_camera_yaw_offset is not None else float(rows[0].get("drone_camera_yaw_offset", 0.0))
    dog_pitch = float(args.robotdog_camera_pitch) if args.robotdog_camera_pitch is not None else float(rows[0].get("robotdog_camera_pitch", -8.0))
    dog_yaw_offset = float(args.robotdog_camera_yaw_offset) if args.robotdog_camera_yaw_offset is not None else float(rows[0].get("robotdog_camera_yaw_offset", 0.0))
    dog_mount = list(args.robotdog_camera_mount) if args.robotdog_camera_mount is not None else [140.0, 0.0, 110.0]
    pose_after = {
        "drone": [row["drone_pose_after_action"] for row in rows],
        "robotdog": [row["robotdog_pose_after_action"] for row in rows],
    }
    infos: dict[str, list[dict[str, Any]]] = {"drone": [], "robotdog": []}
    for index, row in enumerate(rows):
        for agent in ("drone", "robotdog"):
            pose_key = f"{agent}_pose"
            after_key = f"{agent}_pose_after_action"
            bbox_prefix = agent
            bbox = [int(value) for value in row[f"{bbox_prefix}_target_bbox"]]
            center_error, centered = bbox_center_metrics(bbox, int(args.width), int(args.height))
            actual_velocity = realized_base_velocity(row[pose_key], row[after_key], args.dt)
            if agent == "drone":
                action = [float(value) for value in row["drone_env_action"]]
                commanded_velocity = [action[0] / args.dt, action[1] / args.dt, action[3]]
            else:
                action = [float(value) for value in row["robotdog_env_action"]]
                # Ground turn command has the measured BP scale relation
                # delta_yaw_deg = ground_turn_step_gain * command_deg.
                commanded_velocity = [
                    action[1] / UNREAL_UNITS_PER_METER,
                    0.0,
                    math.radians(args.ground_turn_step_gain * action[0]) / args.dt,
                ]
            waypoints, waypoint_mask = local_waypoints(
                pose_after[agent], index, args.training_waypoint_horizon
            )
            info = {
                "step": int(row["step"]),
                "dt": float(args.dt),
                "effective_dt_s": float(args.dt),
                "training_dt_s": float(args.dt),
                "fixed_timestep_seconds": float(args.dt),
                "observation_timestamp_s": float(index * args.dt),
                pose_key: row[pose_key],
                after_key: row[after_key],
                "target_pose": row["target_pose"],
                "target_pose_after_action": row["target_pose_after_action"],
                "target_bbox": bbox,
                "target_visible": bool(row[f"{bbox_prefix}_target_visible"]),
                "target_visibility": float(row[f"{bbox_prefix}_target_visibility"]),
                "target_center_error": center_error,
                "target_centered": centered,
                "target_bbox_source": row.get(f"{agent}_target_bbox_source", "replay_object_mask"),
                "drone_camera_pitch": drone_pitch,
                "drone_camera_yaw_offset": drone_yaw_offset,
                "robotdog_camera_pitch": dog_pitch,
                "robotdog_camera_yaw_offset": dog_yaw_offset,
                "robotdog_camera_mount": dog_mount,
                "dis_to_human": xy_distance_m(row[pose_key], row["target_pose"]),
                "base_velocity": actual_velocity,
                "commanded_base_velocity": commanded_velocity,
                "env_action": action,
                "command_label_source": "uncapped_inverse_fixed_dt_realized",
                "actual_waypoints": waypoints,
                "actual_waypoint_valid_mask": waypoint_mask,
                "actual_waypoint_dt_s": float(args.dt),
                "source_after_error_m": float(row[f"{agent}_after_error_m"]),
                "source_yaw_after_error_deg": float(row[f"{agent}_yaw_after_error_deg"]),
                "collision": False,
                "instruction": instruction,
            }
            if agent == "drone":
                info["drone_action"] = action
            else:
                info["ground_action"] = action
            infos[agent].append(info)
    write_json(output_dir / f"{episode}_drone_info.json", infos["drone"])
    write_json(output_dir / f"{episode}_robotdog_info.json", infos["robotdog"])
    stat = {
        "finish": True,
        "status": "ReplayComplete",
        "success": 1.0,
        "total_step": len(rows),
        "collision": 0.0,
        "instruction": instruction,
        "dt": float(args.dt),
        "training_dt_s": float(args.dt),
        "video_fps": int(round(1.0 / args.dt)),
        "obs_action_alignment": "obs_t_action_t",
        "label_source": "uncapped_inverse_fixed_dt_realized",
        "drone_camera_pitch": drone_pitch,
        "drone_camera_yaw_offset": drone_yaw_offset,
        "robotdog_camera_pitch": dog_pitch,
        "robotdog_camera_yaw_offset": dog_yaw_offset,
        "robotdog_camera_mount": dog_mount,
        "all_steps_retained": True,
        "drone_following_rate": float(np.mean([bool(row["drone_target_visible"]) for row in rows])),
        "robotdog_following_rate": float(np.mean([bool(row["robotdog_target_visible"]) for row in rows])),
    }
    write_json(output_dir / f"{episode}.json", stat)


def main() -> int:
    args = parse_args()
    if args.write_training_records and args.visual_label_mode != "replay_mask":
        raise ValueError(
            "training records require --visual-label-mode replay_mask; "
            "source-recorded boxes are not exact for replay RGB"
        )
    if args.dt <= 0 or args.ue_interval_ms != int(round(args.dt * 1000.0)):
        raise ValueError("fixed replay requires --dt > 0 and --ue-interval-ms = dt * 1000")
    if args.ground_max_forward_feedback_mps < 0:
        raise ValueError("--ground-max-forward-feedback-mps must be non-negative")
    if min(args.drone_b_forward, args.drone_b_lateral, args.drone_yaw_b) <= 0:
        raise ValueError("inverse model b coefficients must be positive")
    if args.training_waypoint_horizon < 1:
        raise ValueError("--training-waypoint-horizon must be positive")
    if args.post_reset_settle_s < 0:
        raise ValueError("--post-reset-settle-s must be non-negative")
    os.environ["UNREALZOO_FIXED_TIMESTEP"] = f"{args.dt:.9g}"
    random.seed(args.seed)
    np.random.seed(args.seed)
    source = args.recorded_dir.expanduser().resolve()
    drone_path, dog_path, stat_path = source / f"{args.episode}_drone_info.json", source / f"{args.episode}_robotdog_info.json", source / f"{args.episode}.json"
    drone_rows, dog_rows = read_json(drone_path), read_json(dog_path)
    stat = read_json(stat_path) if stat_path.is_file() else None
    if not isinstance(drone_rows, list) or not isinstance(dog_rows, list):
        raise ValueError("source drone/dog files must be JSON arrays")
    count = min(len(drone_rows), len(dog_rows))
    if args.max_steps > 0:
        count = min(count, args.max_steps)
    if count < 1:
        raise ValueError("no source steps")
    args.save_dir.mkdir(parents=True, exist_ok=True)
    env_args = build_env_args(args, drone_rows[0], stat if isinstance(stat, dict) else None)
    if args.drone_max_speed_mps is not None:
        env_args.drone_max_speed = float(args.drone_max_speed_mps)
    env_args.top_view_height = None
    config = vars(args).copy()
    config.update({"protocol": "fixed_dt_closed_loop_inverse_dynamics", "source_dir": str(source), "no_per_step_pose_restore": True, "ground_yaw_relation": "delta_yaw_deg = 0.4 * turn_command_deg", "ground_translation_model": "speed[t] affects translation[t+1] when ground_translation_delay_steps=1", "ground_control_mode": args.ground_control_mode, "drone_translation_model": "v_next = a*v_current + b*u (empirical action delay=0)", "drone_yaw_model": "omega_next = a*omega_current + b*u (empirical action delay=0)", "training_record_labels": "realized replay base_velocity; env_action is the exact command supplied to UE", "all_steps_retained": True})
    config["recorded_dir"] = str(source)
    config["save_dir"] = str(args.save_dir)
    write_json(args.save_dir / "replay_config.json", config)
    print(f"[inverse] source={source} episode={args.episode} steps={count} dt={args.dt:.3f}s gpu={args.render_gpu}", flush=True)

    env = make_env(env_args)
    writers: dict[str, cv2.VideoWriter] = {}
    replay_rows: list[dict[str, Any]] = []
    try:
        reset_env(env, env_args)
        # Reset triggers a large asynchronous ProxyAnnotator render pass. A
        # first RGB/mask request during that pass can crash UE's rendering
        # thread on Vulkan; keep the simulator idle until it settles.
        if args.post_reset_settle_s > 0:
            print(f"[reset] settling UE for {args.post_reset_settle_s:.1f}s before camera setup", flush=True)
            time.sleep(float(args.post_reset_settle_s))
        target_id, dog_id, drone_id = classify_coop_agents(env)
        players = env.unwrapped.player_list
        target_name, dog_name, drone_name = players[target_id], players[dog_id], players[drone_id]
        env.unwrapped.unrealcv.set_appearance(target_name, args.human_appearance_id)
        env.unwrapped.unrealcv.set_appearance(dog_name, args.robotdog_appearance_id)
        first_target, first_dog, first_drone = _require(drone_rows, 0, "target_pose"), _require(dog_rows, 0, "robotdog_pose"), _require(drone_rows, 0, "drone_pose")
        restore_pose(env, target_name, first_target)
        restore_pose(env, dog_name, first_dog, lambda yaw: set_ground_yaw(env, dog_name, yaw))
        restore_pose(env, drone_name, first_drone, lambda yaw: maybe_set_drone_yaw(env, drone_name, yaw))
        first_dog_row, first_drone_row = dog_rows[0], drone_rows[0]
        dog_mount = list(args.robotdog_camera_mount) if args.robotdog_camera_mount is not None else [float(v) for v in first_dog_row.get("robotdog_camera_mount", [140, 0, 110])[:3]]
        dog_pitch = float(args.robotdog_camera_pitch) if args.robotdog_camera_pitch is not None else float(first_dog_row.get("robotdog_camera_pitch", -15.0))
        dog_yaw_offset = float(args.robotdog_camera_yaw_offset) if args.robotdog_camera_yaw_offset is not None else float(first_dog_row.get("robotdog_camera_yaw_offset", 0.0))
        drone_pitch = float(args.drone_camera_pitch) if args.drone_camera_pitch is not None else float(first_drone_row.get("drone_camera_pitch", -40.0))
        drone_yaw_offset = float(args.drone_camera_yaw_offset) if args.drone_camera_yaw_offset is not None else float(first_drone_row.get("drone_camera_yaw_offset", 0.0))
        set_robotdog_camera(env, dog_name, dog_id, dog_mount, dog_pitch, dog_yaw_offset, dog_args(env_args))
        set_drone_camera(env, drone_name, drone_id, first_drone, drone_pitch, drone_yaw_offset, drone_args(env_args))
        unrealcv = env.unwrapped.unrealcv
        unrealcv.set_global_time_dilation(1.0)
        unrealcv.set_max_FPS(1.0 / args.dt)
        unrealcv.set_pause()
        if args.visual_label_mode == "replay_mask":
            response = unrealcv.client.request("vrun r.FinishCurrentFrame 1")
            if response is None:
                raise RuntimeError("failed to enable r.FinishCurrentFrame for exact replay masks")
        for name, speed in ((target_name, args.human_max_speed_mps), (dog_name, args.dog_max_speed_mps)):
            unrealcv.set_max_speed(name, float(speed * UNREAL_UNITS_PER_METER))
            unrealcv.set_acceleration(name, float(args.ground_acceleration))
        # Restore again behind the pause barrier. This is deliberately the final restore.
        restore_pose(env, target_name, first_target)
        restore_pose(env, dog_name, first_dog, lambda yaw: set_ground_yaw(env, dog_name, yaw))
        restore_pose(env, drone_name, first_drone, lambda yaw: maybe_set_drone_yaw(env, drone_name, yaw))
        refresh_poses(env)
        previous_actual: dict[str, list[float] | None] = {"target": None, "robotdog": None, "drone": None}
        ground_reverse_mode = {"target": False, "robotdog": False}
        ground_heading_goal: dict[str, float | None] = {"target": None, "robotdog": None}
        ground_speed_models = {"target": AdaptiveGroundSpeedModel(), "robotdog": AdaptiveGroundSpeedModel()}
        paths = {"drone": args.save_dir / f"{args.episode}_drone.mp4", "robotdog": args.save_dir / f"{args.episode}_robotdog.mp4", "global": args.save_dir / f"{args.episode}_global.mp4"}

        for index in range(count):
            before = refresh_poses(env)
            actual_target, actual_dog, actual_drone = list(before[target_id]), list(before[dog_id]), list(before[drone_id])
            target_forward_velocity = (
                float(body_xy_velocity(previous_actual["target"], actual_target, args.dt)[0])
                if previous_actual["target"] is not None
                else 0.0
            )
            dog_forward_velocity = (
                float(body_xy_velocity(previous_actual["robotdog"], actual_dog, args.dt)[0])
                if previous_actual["robotdog"] is not None
                else 0.0
            )
            if args.ground_speed_model == "adaptive_inverse":
                ground_speed_models["target"].update(target_forward_velocity)
                ground_speed_models["robotdog"].update(dog_forward_velocity)
            source_target_before, source_dog_before = _require(drone_rows, index, "target_pose"), _require(dog_rows, index, "robotdog_pose")
            reference_target, reference_dog, reference_drone = _reference(drone_rows, index, "target_pose"), _reference(dog_rows, index, "robotdog_pose"), _reference(drone_rows, index, "drone_pose")
            reference_target_next = _reference(drone_rows, index + 1, "target_pose") if index + 1 < count else reference_target
            reference_dog_next = _reference(dog_rows, index + 1, "robotdog_pose") if index + 1 < count else reference_dog
            lookahead_index = min(index + max(1, args.ground_heading_lookahead_steps), count - 1)
            reference_target_lookahead = _reference(drone_rows, lookahead_index, "target_pose")
            reference_dog_lookahead = _reference(dog_rows, lookahead_index, "robotdog_pose")
            target_action, target_info = ground_control(
                actual_target, source_target_before, reference_target, reference_target_next, args.dt,
                args.ground_turn_step_gain, args.human_max_speed_mps, args.ground_max_turn_deg,
                args.ground_translation_delay_steps, args.ground_position_feedback_time_s, args.ground_control_mode,
                args.ground_vector_min_speed_mps, args.ground_vector_max_heading_delta_deg,
                reference_target_lookahead, ground_reverse_mode["target"], args.ground_reverse_enter_deg,
                args.ground_reverse_exit_deg, ground_heading_goal["target"], args.ground_heading_goal_rate_deg,
                args.ground_turn_slowdown_floor, args.ground_heading_deadband_deg,
                args.ground_max_forward_feedback_mps,
                args.ground_speed_model,
                ground_speed_models["target"] if args.ground_speed_model == "adaptive_inverse" else None,
                target_forward_velocity,
            )
            dog_action, dog_info = ground_control(
                actual_dog, source_dog_before, reference_dog, reference_dog_next, args.dt,
                args.ground_turn_step_gain, args.dog_max_speed_mps, args.ground_max_turn_deg,
                args.ground_translation_delay_steps, args.ground_position_feedback_time_s, args.ground_control_mode,
                args.ground_vector_min_speed_mps, args.ground_vector_max_heading_delta_deg,
                reference_dog_lookahead, ground_reverse_mode["robotdog"], args.ground_reverse_enter_deg,
                args.ground_reverse_exit_deg, ground_heading_goal["robotdog"], args.ground_heading_goal_rate_deg,
                args.ground_turn_slowdown_floor, args.ground_heading_deadband_deg,
                args.ground_max_forward_feedback_mps,
                args.ground_speed_model,
                ground_speed_models["robotdog"] if args.ground_speed_model == "adaptive_inverse" else None,
                dog_forward_velocity,
            )
            ground_reverse_mode["target"] = bool(target_info["reverse_mode"])
            ground_reverse_mode["robotdog"] = bool(dog_info["reverse_mode"])
            ground_heading_goal["target"] = target_info["heading_goal_deg"]
            ground_heading_goal["robotdog"] = dog_info["heading_goal_deg"]
            if args.ground_speed_model == "adaptive_inverse":
                ground_speed_models["target"].set_command(float(target_action[1]) / UNREAL_UNITS_PER_METER)
                ground_speed_models["robotdog"].set_command(float(dog_action[1]) / UNREAL_UNITS_PER_METER)
            drone_action, drone_info = drone_control(actual_drone, previous_actual["drone"], reference_drone, args.dt, args)
            # Observations are captured while UE is paused, before action t.
            # UE5.6's object-mask render pass can crash the Vulkan rendering
            # thread on some maps.  Source recordings already contain bbox
            # and visibility labels, so use them by default while preserving
            # replay RGB/video and all dynamics metrics.
            observation = None
            masks: list[np.ndarray | None] | None = None
            drone_visibility, drone_visible, drone_bbox = 0.0, False, [0, 0, 0, 0]
            dog_visibility, dog_visible, dog_bbox = 0.0, False, [0, 0, 0, 0]
            if args.save_video or args.write_training_records:
                set_robotdog_camera(env, dog_name, dog_id, dog_mount, dog_pitch, dog_yaw_offset, dog_args(env_args))
                set_drone_camera(env, drone_name, drone_id, actual_drone, drone_pitch, drone_yaw_offset, drone_args(env_args))
                observation, masks = capture_color_mask_snapshot_stable(
                    env,
                    include_masks=args.write_training_records and args.visual_label_mode == "replay_mask",
                    attempts=args.snapshot_retries,
                    mode=args.snapshot_mode,
                    render_sync_s=args.snapshot_render_sync_s if args.visual_label_mode == "replay_mask" else 0.0,
                )
                if args.write_training_records:
                    if args.visual_label_mode == "replay_mask":
                        drone_visibility, drone_visible, drone_bbox = object_mask_ratio_and_bbox(
                            env, env.unwrapped.cam_list[drone_id], target_name, mask_img=masks[drone_id]
                        )
                        dog_visibility, dog_visible, dog_bbox = object_mask_ratio_and_bbox(
                            env, env.unwrapped.cam_list[dog_id], target_name, mask_img=masks[dog_id]
                        )
                    else:
                        drone_visual = drone_rows[index]
                        dog_visual = dog_rows[index]
                        drone_bbox = list(drone_visual.get("target_bbox", [0, 0, 0, 0]))
                        dog_bbox = list(dog_visual.get("target_bbox", [0, 0, 0, 0]))
                        drone_visibility = float(drone_visual.get("target_visibility", 0.0))
                        dog_visibility = float(dog_visual.get("target_visibility", 0.0))
                        drone_visible = bool(drone_visual.get("target_visible", False))
                        dog_visible = bool(dog_visual.get("target_visible", False))
            if args.save_video:
                if observation is None:
                    raise RuntimeError("video requested but no paused observation was captured")
                write_video_frame(writers, "drone", paths["drone"], observation[drone_id], 1.0 / args.dt)
                write_video_frame(writers, "robotdog", paths["robotdog"], observation[dog_id], 1.0 / args.dt)
                if args.write_global_video:
                    frame = get_global_frame(env, env_args, actual_target, actual_dog, actual_drone)
                    if frame is not None:
                        write_video_frame(writers, "global", paths["global"], frame, 1.0 / args.dt)
            actions: list[list[float] | None] = [None] * len(players)
            actions[target_id], actions[dog_id], actions[drone_id] = target_action, dog_action, drone_action
            after, pulse = fixed_step(env, actions)
            after_target, after_dog, after_drone = list(after[target_id]), list(after[dog_id]), list(after[drone_id])
            row = {
                "step": index + 1, "dt": args.dt, "pulse_wall_time_s": pulse,
                "target_pose": actual_target, "target_pose_after_action": after_target, "source_target_pose_after_action": reference_target,
                "robotdog_pose": actual_dog, "robotdog_pose_after_action": after_dog, "source_robotdog_pose_after_action": reference_dog,
                "drone_pose": actual_drone, "drone_pose_after_action": after_drone, "source_drone_pose_after_action": reference_drone,
                "target_env_action": target_action, "robotdog_env_action": dog_action, "drone_env_action": drone_action,
                "target_inverse": target_info, "robotdog_inverse": dog_info, "drone_inverse": drone_info,
                "drone_target_bbox": drone_bbox, "drone_target_visible": drone_visible, "drone_target_visibility": drone_visibility,
                "robotdog_target_bbox": dog_bbox, "robotdog_target_visible": dog_visible, "robotdog_target_visibility": dog_visibility,
                "drone_target_bbox_source": "replay_object_mask" if args.visual_label_mode == "replay_mask" else "source_recording",
                "robotdog_target_bbox_source": "replay_object_mask" if args.visual_label_mode == "replay_mask" else "source_recording",
                "target_after_error_m": pose_error_m(after_target, reference_target), "robotdog_after_error_m": pose_error_m(after_dog, reference_dog), "drone_after_error_m": pose_error_m(after_drone, reference_drone),
                "target_yaw_after_error_deg": yaw_error_deg(after_target, reference_target), "robotdog_yaw_after_error_deg": yaw_error_deg(after_dog, reference_dog), "drone_yaw_after_error_deg": yaw_error_deg(after_drone, reference_drone),
            }
            replay_rows.append(row)
            previous_actual.update({"target": actual_target, "robotdog": actual_dog, "drone": actual_drone})
            if index < 5 or (index + 1) % 25 == 0:
                print(f"[step {index + 1}] target={row['target_after_error_m']:.3f}m dog={row['robotdog_after_error_m']:.3f}m drone={row['drone_after_error_m']:.3f}m sat=({int(any(drone_info['translation_saturated']))},{int(drone_info['yaw_saturated'])})", flush=True)
    finally:
        for writer in writers.values():
            writer.release()
        try:
            env.close()
        except Exception:
            pass

    metric = lambda key: np.asarray([float(row[key]) for row in replay_rows], dtype=float)
    summary = {"protocol": "fixed_dt_closed_loop_inverse_dynamics", "source_dir": str(source), "episode": str(args.episode), "steps": len(replay_rows), "dt": args.dt}
    for agent in ("target", "robotdog", "drone"):
        for key, label in ((f"{agent}_after_error_m", "position"), (f"{agent}_yaw_after_error_deg", "yaw")):
            values = metric(key)
            summary[f"{agent}_{label}_error"] = {"mean": float(values.mean()), "p95": float(np.quantile(values, .95)), "max": float(values.max())}
    summary["saturation_rate"] = {
        "target": float(np.mean([r["target_inverse"]["speed_saturated"] or r["target_inverse"]["turn_saturated"] for r in replay_rows])),
        "robotdog": float(np.mean([r["robotdog_inverse"]["speed_saturated"] or r["robotdog_inverse"]["turn_saturated"] for r in replay_rows])),
        "drone_translation": float(np.mean([any(r["drone_inverse"]["translation_saturated"]) for r in replay_rows])),
        "drone_yaw": float(np.mean([r["drone_inverse"]["yaw_saturated"] for r in replay_rows])),
    }
    write_json(args.save_dir / f"{args.episode}_inverse_replay.json", replay_rows)
    write_json(args.save_dir / "summary.json", summary)
    if args.write_training_records:
        source_instruction = (
            str(stat.get("instruction"))
            if isinstance(stat, dict) and stat.get("instruction")
            else "Track the person collaboratively while keeping them visible."
        )
        write_training_records(args.save_dir, str(args.episode), replay_rows, args, source_instruction)
    csv_path = args.save_dir / f"{args.episode}_step_metrics.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        fields = ["step", "target_after_error_m", "robotdog_after_error_m", "drone_after_error_m", "target_yaw_after_error_deg", "robotdog_yaw_after_error_deg", "drone_yaw_after_error_deg", "pulse_wall_time_s"]
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows([{key: row[key] for key in fields} for row in replay_rows])
    plot_results(replay_rows, args.save_dir / "trajectory_error_saturation.png")
    print(json.dumps(summary, ensure_ascii=False, indent=2), flush=True)
    print(f"[done] output={args.save_dir}", flush=True)
    return 0


